/** Default candidate-image check is offline. Speech access probing is explicitly opt-in. */
import {execFile} from 'node:child_process';
import {pathToFileURL} from 'node:url';
import {promisify} from 'node:util';
import {readCoralOpenAISecret} from './coral-openai-secret.mjs';
import {createCoralRealtimeProvider} from './coral-tts-realtime-contract.mjs';

const speechModel='gpt-4o-mini-tts';
const api='https://api.openai.com/v1';

export async function probeCoralSpeechAccess({fetcher=fetch,readSecret=readCoralOpenAISecret}={}){
  const headers={Authorization:'Bearer '+readSecret(),'Content-Type':'application/json'};
  const options={headers,redirect:'error'};
  try{
    const model=await fetcher(api+'/models/'+speechModel,{...options,signal:AbortSignal.timeout(12000)});
    const modelVisible=model.status===200&&(await model.json()).id===speechModel;
    if(model.status!==200)await model.body?.cancel().catch(()=>{});
    if(!modelVisible)return {model_http:model.status,speech_http:null,access_confirmed:false,voice_qualified:false};

    // The required input is deliberately absent. No audio can be generated by this check.
    const speech=await fetcher(api+'/audio/speech',{
      ...options,method:'POST',signal:AbortSignal.timeout(12000),
      body:JSON.stringify({model:speechModel,voice:'coral'}),
    });
    const error=speech.status===400?(await speech.json()).error:null;
    if(speech.status!==400)await speech.body?.cancel().catch(()=>{});
    return {
      model_http:model.status,
      speech_http:speech.status,
      access_confirmed:error?.code==='missing_required_parameter'&&error.param==='input',
      voice_qualified:false,
    };
  }catch{
    throw Error('CORAL_SPEECH_ACCESS_CHECK_FAILED');
  }
}

async function main(args){
  if(process.platform!=='linux'||process.getuid()!==1000)throw Error('AUDIO_CANDIDATE_USER');
  if(args.length===1&&args[0]==='--check-speech-access'){
    const result=await probeCoralSpeechAccess();
    console.log(JSON.stringify(result));
    if(!result.access_confirmed)process.exitCode=1;
    return;
  }
  if(args.length)throw Error('AUDIO_CANDIDATE_ARGUMENTS');
  let disabled=false;try{createCoralRealtimeProvider();}catch(e){disabled=e.message==='CORAL_REAL_PROVIDER_DISABLED';}if(!disabled)throw Error('AUDIO_CANDIDATE_PROVIDER');
  const tools={};for(const name of ['ffmpeg','ffprobe'])tools[name]=(await promisify(execFile)(name,['-version'],{timeout:10000,maxBuffer:20000})).stdout.split('\n')[0];
  console.log(JSON.stringify({contract:'cdc-coral-audio-image-preflight-v1',uid:process.getuid(),tools,real_provider_disabled:disabled,http_listener_started:false,secret_contents_read:false,provider_calls:0}));
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  await main(process.argv.slice(2));
}
